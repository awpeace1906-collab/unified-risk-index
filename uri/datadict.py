"""Generate the Phase 1 EHR extraction specification from the engine's own mappings.

    python -m uri.datadict > docs/DATA_DICTIONARY.md

The document is what the data warehouse / research IT team needs for the
retrospective FHIR bulk export: which resources, which codes, which fields.
A test keeps the committed copy in sync with the code.
"""

from __future__ import annotations

from collections import defaultdict

from . import fhir, registry
from .config import Config
from .events import PARAMETERS, RESP_SUPPORT


def render() -> str:
    cfg = Config()
    out = []
    w = out.append
    w("# Data dictionary: Phase 1 EHR extraction")
    w("")
    w("Generated by `python -m uri.datadict` from the engine's mappings; do not edit by hand.")
    w("This is the specification for the retrospective export the Phase 1 derivation replays")
    w("(`python -m uri replay export.ndjson --log snapshots.jsonl --outcomes-out outcomes.csv`).")
    w("")
    w("## Request")
    w("")
    w("* **Population:** consecutive adult (>= 18 y) ED encounters over the study period, including")
    w("  those discharged from the ED (the composite outcome is only possible after admission, but")
    w("  denominators need every encounter).")
    w("* **Format:** FHIR R4 Bulk Data export (NDJSON), one file per resource type, or an equivalent")
    w("  flat extract carrying the same codes and timestamps.")
    w("* **Resources:** `Patient`, `Encounter`, `Observation` (vital-signs and laboratory),")
    w("  `Condition` (problem list and encounter diagnoses), `MedicationRequest`,")
    w("  `MedicationStatement`, `MedicationAdministration`, `Procedure`, `Consent`.")
    w("* **Window:** from 365 days before each ED arrival for creatinine, hemoglobin, platelets,")
    w("  bilirubin and pCO2 (pre-episode baselines), 90 days for encounters and procedures (recent")
    w("  hospitalization / surgery), to 48 h after arrival (outcomes).")
    w("* **Units of analysis:** one ED encounter per subject id. A patient with several ED")
    w("  encounters in the period should appear once per encounter (e.g. `patientid-encounterid`),")
    w("  because outcomes and calibration rows are taken from each subject's latest episode.")
    w("* **Timestamps:** observation/effective times, not result-filed times, wherever both exist.")
    w("* **De-identification:** shift dates consistently per patient if required; intervals are all")
    w("  the engine needs.")
    w("")

    w("## Observations (LOINC)")
    w("")
    w("| Parameter | Category | Canonical unit | LOINC codes |")
    w("|---|---|---|---|")
    by_param = defaultdict(list)
    for code, param in fhir.LOINC_MAP.items():
        if param.startswith("troponin:"):  # assay-specific codes, one parameter
            param, code = "troponin", f"{code} ({param.split(':', 1)[1]})"
        by_param[param].append(code)
    for param, (category, unit) in PARAMETERS.items():
        codes = by_param.get(param, [])
        if param == "o2_supplemental":
            codes = by_param.get("o2_flow", [])
        if param in ("sbp", "dbp"):
            codes = codes + [f"{fhir.BP_PANEL} (panel component)"]
        unit = unit.replace("|", "/")  # keep the markdown table intact
        w(f"| `{param}` | {category} | {unit} | {', '.join(codes) or 'site-specific (see below)'} |")
    w("")
    w("Units are converted on ingest for: temperature (°F), glucose and BUN (mmol/L), creatinine")
    w("(µmol/L), hemoglobin (g/L), lactate (mg/dL), fibrinogen (g/L), FiO₂ (fraction). Any other")
    w("unit is taken as canonical.")
    w("")
    w("Troponin from any assay (high-sensitivity or conventional, T or I; ng/L, ng/mL or µg/L) is")
    w("stored as a multiple of that assay's 99th-percentile upper reference limit, so assays are")
    w("interchangeable. Set each assay's URL to your laboratory's in `troponin_urls`: "
      + ", ".join(f"{k} {v:g} ng/L" for k, v in cfg.troponin_urls.items()) + " by default. A local")
    w("troponin code maps with `local_codes`, e.g. `\"urn:oid:...|TROP\": \"troponin:tni\"`.")
    w("")

    w("## Site-specific flowsheet rows (map in `local_codes`)")
    w("")
    w("| Target | What to map | Notes |")
    w("|---|---|---|")
    w("| `resp_support` | O₂ delivery device / ventilation mode row | text is classified: "
      + "; ".join(f"{k} = {v}" for k, v in RESP_SUPPORT.items()) + " |")
    w("| `cfs` | Clinical Frailty Scale (1-9) | nursing frailty screen |")
    w("| `outcome:rrt` | rapid response team activation | flowsheet row or procedure code |")
    w("| `urine_ml_hr` | urine output, mL/h | intake/output flowsheet (not yet scored) |")
    w("")

    w("## Conditions (ICD-10-CM prefixes)")
    w("")
    w("Problem list and encounter diagnoses with clinicalStatus and recorded/onset dates.")
    w("")
    w("| Factor | Label | ICD-10-CM prefixes |")
    w("|---|---|---|")
    for f in registry.COMORBIDITIES + registry.CHARLSON:
        if f.icd10:
            w(f"| `{f.id}` | {f.label} | {', '.join(f.icd10)} |")
    w("")
    w("Derived (no diagnosis code): " + "; ".join(
        f"`{f.id}` ({f.derived})" for f in registry.COMORBIDITIES if f.derived) + ".")
    w("")

    w("## Medications")
    w("")
    w("Matched on ingredient names in the medication text / RxNorm display. Include status,")
    w("authored / effective times and, for loop diuretics, the dose in mg.")
    w("")
    w("| Class | Ingredients |")
    w("|---|---|")
    for f in registry.MEDICATIONS:
        w(f"| `{f.id}` | {', '.join(f.ingredients)} |")
    w("")

    w("## Procedures, encounters, consent, patient")
    w("")
    w("| Item | Source | Codes / fields |")
    w("|---|---|---|")
    w("| Emergent intubation (outcome) | Procedure | "
      + ", ".join(f"{s.rsplit('/', 1)[-1]} {c}" for s, c in sorted(fhir.INTUBATION_CODES)) + " |")
    w(f"| Recent surgery | Procedure | category {fhir.SURGICAL_CATEGORY[1]} (surgical procedure), performed date |")
    w("| Visit boundaries | Encounter | class " + "/".join(sorted(fhir.VISIT_CLASSES))
      + ", status, period.start / period.end (ED arrival through the linked admission) |")
    w("| Recent hospitalization | Encounter | class " + "/".join(sorted(fhir.INPATIENT_CLASSES))
      + ", status finished, period.end |")
    w("| ICU transfer (outcome) | Encounter.location | location display matching: "
      + ", ".join(cfg.icu_location_patterns) + "; location period.start |")
    w("| Vasopressor start (outcome) | MedicationAdministration | first administration of "
      + ", ".join(fhir.PRESSOR_START) + " |")
    w("| Death (outcome) | Patient | deceasedDateTime |")
    w("| Age, language | Patient | birthDate; communication.language + preferred; interpreterRequired extension |")
    w("| Advance directive | Consent | category acd / LOINC 42348-3, status |")
    w("")

    w("## Outcome definitions (study protocol)")
    w("")
    w("Composite decompensation = first of unplanned ICU transfer, RRT activation, emergent")
    w("intubation, vasopressor initiation, in-hospital death, counted at 6 / 12 / 24 / 36 / 48 h")
    w("from triage. Planned ICU admissions need a site rule (ED disposition order or chart review)")
    w("to be excluded.")
    w("")
    return "\n".join(out)


if __name__ == "__main__":
    print(render())
